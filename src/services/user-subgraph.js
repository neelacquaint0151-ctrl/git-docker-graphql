import express from 'express';
import http from 'http';
import cors from 'cors';
import dotenv from 'dotenv';
import { ApolloServer } from '@apollo/server';
import { expressMiddleware } from '@apollo/server/express4';
import { buildSubgraphSchema } from '@apollo/subgraph';
import gql from 'graphql-tag';

import { userResolver } from '../graphql/resolvers/user.resolver.js';
import { postResolver } from '../graphql/resolvers/post.resolver.js';
import { createPostLoader } from '../dataloaders/post.loader.js';
import { redis } from '../config/redis.js';
import { prisma } from '../db/prisma.js';

dotenv.config();

const app = express();
const httpServer = http.createServer(app);

// Background Redis Stream Consumer for Inter-Service Events
async function consumeAuthEvents() {
  let lastId = '$'; // Start listening for new events only
  console.log('🎧 [User Service] Started listening for Redis Stream auth-events...');

  while (true) {
    try {
      // Blocking read on 'auth-events' stream
      const results = await redis.xread('BLOCK', 5000, 'STREAMS', 'auth-events', lastId);

      if (results) {
        const [stream] = results;
        const messages = stream[1];

        for (const [id, fields] of messages) {
          lastId = id;
          // Parse key-value pairs from stream array
          const eventData = {};
          for (let i = 0; i < fields.length; i += 2) {
            eventData[fields[i]] = fields[i + 1];
          }

          if (eventData.event === 'USER_VERIFIED') {
            console.log(`📥 [Event Consumer] Handling USER_VERIFIED event for phone: ${eventData.phone}`);
            
            // Auto-create user in Postgres upon OTP verification event
            const email = `user_${eventData.phone.replace(/[^0-9]/g, '')}@autogenerated.com`;
            await prisma.user.upsert({
              where: { email },
              update: {},
              create: {
                name: `Verified User (${eventData.phone})`,
                email,
              },
            });
            console.log(`✅ [User Service] Auto-created user profile for ${email}`);
          }
        }
      }
    } catch (error) {
      console.error('Redis Stream Consumer error:', error.message);
      await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }
}

// Start background event worker
consumeAuthEvents();

const typeDefs = gql`
  type User {
    id: ID!
    name: String
    role: String
  }

  type DBUser {
    id: ID!
    name: String!
    email: String!
    posts: [DBPost!]!
  }

  type DBPost {
    id: ID!
    title: String!
    authorId: Int!
  }

  type Query {
    hello: String
    healthCheck: String
    getUser(id: ID!): User
    users: [DBUser!]!
  }

  type Mutation {
    updateUser(id: ID!, name: String, role: String): User
    createUser(name: String!, email: String!): DBUser!
    createPost(title: String!, authorId: Int!): DBPost!
  }
`;

const resolvers = {
  Query: { ...userResolver.Query },
  DBUser: { ...userResolver.DBUser },
  Mutation: { ...userResolver.Mutation, ...postResolver.Mutation },
};

const server = new ApolloServer({
  schema: buildSubgraphSchema({ typeDefs, resolvers }),
});

await server.start();

app.use(
  '/graphql',
  cors(),
  express.json(),
  expressMiddleware(server, {
    context: async () => ({ postLoader: createPostLoader() }),
  })
);

const PORT = process.env.USER_SERVICE_PORT || 4002;
httpServer.listen(PORT, () => console.log(`👤 User Subgraph ready at http://localhost:${PORT}/graphql`));